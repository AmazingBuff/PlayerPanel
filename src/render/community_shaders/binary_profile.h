    [[nodiscard]] inline bool matches_identity(std::uint32_t timestamp, std::uint32_t size,
        std::span<std::uint8_t const> guid, std::uint32_t age)
    {
        return timestamp == Timestamp && size == Image_Size && age == 1 && guid.size() == Pdb_Guid.size() &&
            std::memcmp(guid.data(), Pdb_Guid.data(), Pdb_Guid.size()) == 0;
    }

    [[nodiscard]] inline bool matches_entries(std::span<std::uint8_t const> image)
    {
        for (auto const& entry : Entries)
            if (entry.rva == 0 || entry.rva > image.size() || entry.prefix.size() > image.size() - entry.rva ||
                std::memcmp(image.data() + entry.rva, entry.prefix.data(), entry.prefix.size()) != 0)
                return false;
        return true;
    }
