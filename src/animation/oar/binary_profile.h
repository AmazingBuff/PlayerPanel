    [[nodiscard]] inline bool matches_query(QueryProfile const& profile, std::span<std::uint8_t const> image)
    {
        return std::ranges::all_of(profile.entries, [&](QueryEntry const& entry)
        {
            return entry.rva != 0 && entry.rva <= image.size() &&
                entry.prefix.size() <= image.size() - entry.rva &&
                std::memcmp(image.data() + entry.rva, entry.prefix.data(), entry.prefix.size()) == 0;
        });
    }

